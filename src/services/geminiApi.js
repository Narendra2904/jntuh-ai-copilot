/**
 * Gemini 2.5 Flash REST API Service
 * Powers the 4-in-1 AI Academic & Career Co-Pilot Suite
 */

const GEMINI_MODEL = "gemini-2.5-flash";
const BASE_URL = `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent`;

/**
 * Retrieve Active Gemini API Key
 */
export function getActiveApiKey() {
  const localKey = localStorage.getItem("gemini_api_key");
  if (localKey && localKey.trim().length > 10) return localKey.trim();

  const envKey = import.meta.env.VITE_GEMINI_API_KEY;
  if (envKey && envKey.trim().length > 10) return envKey.trim();

  return "";
}

export function saveApiKey(key) {
  if (key && key.trim()) {
    localStorage.setItem("gemini_api_key", key.trim());
  } else {
    localStorage.removeItem("gemini_api_key");
  }
}

/**
 * Deterministic Hash Key for LocalStorage Caching
 */
function createCacheKey(hallTicket, toolId, params = {}) {
  const raw = `${hallTicket || "ANON"}_${toolId}_${JSON.stringify(params)}`;
  let hash = 5381;
  for (let i = 0; i < raw.length; i++) {
    hash = ((hash << 5) + hash) + raw.charCodeAt(i);
    hash = hash & hash;
  }
  return `jntuh_ai_cache_${Math.abs(hash)}`;
}

/**
 * Low-level Gemini REST API caller
 */
async function callGemini(prompt, systemInstruction = null) {
  const apiKey = getActiveApiKey();
  if (!apiKey) {
    throw new Error("KEY_REQUIRED");
  }

  const payload = {
    contents: [
      {
        role: "user",
        parts: [{ text: prompt }]
      }
    ],
    generationConfig: {
      temperature: 0.65,
      topK: 40,
      topP: 0.95,
      maxOutputTokens: 2500
    }
  };

  if (systemInstruction) {
    payload.systemInstruction = {
      parts: [{ text: systemInstruction }]
    };
  }

  const res = await fetch(`${BASE_URL}?key=${apiKey}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload)
  });

  if (!res.ok) {
    let errMessage = `HTTP ${res.status}: ${res.statusText}`;
    try {
      const errJson = await res.json();
      if (errJson?.error?.message) {
        errMessage = errJson.error.message;
      }
    } catch (e) {
      // fallback
    }

    if (res.status === 400 || res.status === 403 || errMessage.toLowerCase().includes("key")) {
      throw new Error(`API_KEY_INVALID: ${errMessage}`);
    } else if (res.status === 429) {
      throw new Error("RATE_LIMIT: Gemini free tier quota temporarily reached. Please retry in a moment.");
    }
    throw new Error(errMessage);
  }

  const data = await res.json();
  const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) throw new Error("No response content generated by Gemini.");
  return text;
}

/**
 * Helper to build common student context string
 */
function buildStudentContext(student) {
  const subjectsList = student.latestSubjects.map(s => 
    `- [${s.semester}] ${s.subjectCode}: ${s.subjectName} | Grade: ${s.grade} (GP: ${s.gradePoint}) | Cr: ${s.creditsNum} | Status: ${s.isPass ? "PASS" : "FAIL (SUPPLY)"}`
  ).join("\n");

  const backlogsList = student.backlogs.length > 0 
    ? student.backlogs.map(b => `* ${b.subjectCode} - ${b.subjectName} (${b.creditsNum} Cr) [Int: ${b.internalMarks || "-"}, Ext: ${b.externalMarks || "-"}]`).join("\n")
    : "None (Zero active backlogs 🎉)";

  return `
STUDENT PROFILE:
- Name: ${student.name}
- Hall Ticket: ${student.hallTicket}
- Branch: ${student.branch}
- College: ${student.college} (Code: ${student.collegeCode})
- Regulation: ${student.profile.regulation} (${student.profile.entryType})
- Current Overall CGPA: ${student.cgpaString} / 10.0
- Total Completed Semesters: ${student.completedSemesters} of ${student.profile.totalSemesters}
- Credits Earned: ${student.earnedCredits} / ${student.totalCreditsRequired}
- Remaining Credits: ${student.remainingCredits}

TRANSCRIPT SUMMARY:
${subjectsList}

ACTIVE BACKLOGS:
${backlogsList}
`;
}

/**
 * 1. AI Academic Strategist Tool
 */
export async function runAcademicStrategist(student, bypassCache = false) {
  const cacheKey = createCacheKey(student.hallTicket, "strategist");
  if (!bypassCache) {
    const cached = localStorage.getItem(cacheKey);
    if (cached) return { content: cached, cached: true };
  }

  const prompt = `
${buildStudentContext(student)}

TASK:
You are an expert JNTUH B.Tech Academic Advisor & Exam Strategist.
Generate a high-impact, actionable academic breakdown in clean GitHub-Flavored Markdown covering:

### 1. 📊 GPA Strength & Leverage Matrix
- Analyze the student's highest performance areas (Grades O, A+, A).
- Pinpoint the exact 3-credit and 4-credit bottleneck subjects dragging down the CGPA (Grades C, D, P, or F) and explain their mathematical leverage.

### 2. 🛡️ Backlog & Grade Recovery Roadmap
- If backlogs exist: Rank them in priority order for clearing during the next supply examination cycle based on prerequisite impact and credit weight.
- Clearance blueprint: The 3-Unit Syllabus Mastery strategy, internal marks buffer, the 26/75 external pass threshold, and step-marking tips for university evaluators.
- If zero backlogs: Provide guidance on maintaining consistency, aiming for university honors/distinction, or boosting low-grade core electives.

### 3. 📅 4-Week Pre-Exam Preparation Sprint
- A week-by-week study breakdown tailored to JNTUH semester exams.
`;

  const content = await callGemini(prompt, "You are an elite, empathetic JNTUH Academic Mentor with deep knowledge of R18 and R22 regulations.");
  localStorage.setItem(cacheKey, content);
  return { content, cached: false };
}

/**
 * 2. Interactive "What-If" CGPA Simulator Tool
 */
export async function runWhatIfSimulation(student, targetCgpa, upcomingCredits = null, bypassCache = false) {
  const creditsToConsider = upcomingCredits || student.remainingCredits || 40;
  const cacheKey = createCacheKey(student.hallTicket, "whatif", { targetCgpa, creditsToConsider });
  
  if (!bypassCache) {
    const cached = localStorage.getItem(cacheKey);
    if (cached) return { content: cached, cached: true };
  }

  // Exact math
  const currentEarnedCredits = student.earnedCredits;
  const currentTotalPoints = student.overallCgpa * currentEarnedCredits;
  const finalTotalCredits = currentEarnedCredits + creditsToConsider;
  const targetTotalPoints = targetCgpa * finalTotalCredits;
  const neededPoints = targetTotalPoints - currentTotalPoints;
  const neededSgpa = creditsToConsider > 0 ? (neededPoints / creditsToConsider) : 0;
  const maxPossibleCgpa = ((currentTotalPoints + (10 * creditsToConsider)) / finalTotalCredits).toFixed(2);
  const isFeasible = neededSgpa <= 10.0;

  const prompt = `
${buildStudentContext(student)}

SIMULATION PARAMETERS:
- Current CGPA: ${student.cgpaString} across ${currentEarnedCredits} credits.
- Target CGPA Goal: ${targetCgpa}
- Upcoming Credits Evaluated: ${creditsToConsider} credits (across ~${student.remainingSemesters} remaining semesters).
- Mathematically Required Average SGPA: ${neededSgpa.toFixed(2)}
- Maximum Achievable CGPA (with 10.0 in all future credits): ${maxPossibleCgpa}
- Feasibility: ${isFeasible ? "Mathematically Possible" : "Mathematically Ceiling Exceeded"}

TASK:
Provide a realistic JNTUH B.Tech mentor simulation report in GitHub-Flavored Markdown:

### 1. 🎯 Feasibility & Target Breakdown
- Clear verdict on whether ${targetCgpa} is achievable.
- Explain the needed SGPA (${neededSgpa.toFixed(2)}) across the upcoming ${creditsToConsider} credits.
- If unfeasible, adjust to the realistic maximum achievable ceiling (${maxPossibleCgpa}).

### 2. 📋 Target Grade Distribution Plan
- Outline the exact combination of grades (e.g. 3 subjects with 'O', 2 with 'A+') needed per semester to secure this SGPA.

### 3. 💡 High-Yield Semester Strategy
- Practical advice on lab courses, mini-projects, and theory subject prioritization where high grade points are easiest to harvest.
`;

  const content = await callGemini(prompt, "You are a precise JNTUH Academic Calculator and Strategic Mentor.");
  localStorage.setItem(cacheKey, content);
  return { content, cached: false, neededSgpa: neededSgpa.toFixed(2), isFeasible, maxPossibleCgpa };
}

